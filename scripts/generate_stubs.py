"""Generate type stubs for the library, and audit the annotations behind them.

Why this script exists
======================

The library is annotated inline and ships a ``py.typed`` marker, so a type
checker reads the annotations straight out of the source and no stub file is
needed to use it. That is the right arrangement: one copy of every signature,
in the file that implements it, where it cannot fall behind.

Two things still want stubs, and both are why this script exists.

The first is tooling that cannot read inline annotations. Some editors, some
older checkers, and some build systems consume a stub tree and nothing else.
Generating one on demand serves them without adding a second copy of every
signature to the repository, which is the thing worth avoiding.

The second, and the more useful in practice, is the audit. Producing a stub
means walking every public signature and writing down its annotations, which
is exactly the walk needed to answer whether any of them are missing. A
parameter with no annotation and a routine with no return annotation are both
invisible in normal use and both defeat the purpose of shipping a typed
package, so the check mode reports them.

How the stubs are produced
==========================

By parsing the source, not by importing it. Two reasons:

Importing executes module level code, which for a partially built library
means the generation depends on which packages happen to be implemented. A
parse works on any file that is syntactically valid, including one whose
dependencies are not written yet.

An imported object has lost the source form of its annotations. A default of
``()`` becomes an empty tuple, a string annotation stays a string, and a
union written with a vertical bar has already been evaluated. The parse keeps
what the author wrote, which is what a stub is supposed to record.

The mypy stub generator is used instead when --use-stubgen is given, for a
cross check: two independent renderings of the same signatures that disagree
mean one of them is wrong, and that is worth knowing.

What is emitted
===============

For every module, a stub carrying the license notice, the module's own import
statements verbatim, then its public classes and functions with their
signatures and no bodies. A docstring is dropped, because a stub is read by a
checker rather than by a person, and the reference is generated from the
source. A private name is dropped unless --include-private is given.

Usage
=====

    scripts/generate_stubs.py                     write to build/stubs
    scripts/generate_stubs.py --output tmp/stubs
    scripts/generate_stubs.py --check             audit only, write nothing
    scripts/generate_stubs.py --diff              compare against the output
    scripts/generate_stubs.py --print discretus.core.element
    scripts/generate_stubs.py --use-stubgen       delegate to mypy

Exit status
===========

    0   the stubs were written, or the audit found nothing
    1   the audit found a missing annotation, or a comparison differed
    2   the command line was wrong, or a requested tool is absent
"""

