def source_files() -> List[pathlib.Path]:
    """Return the modules to generate stubs for, in a stable order.

    Returns:
        Every Python file under the package, sorted, with the caches left
        out. A file of zero length is included: it is a placeholder for a
        package that is not written yet, and a stub tree that keeps its
        shape is easier to compare against a later one.
    """
    return sorted(
        path for path in PACKAGE_ROOT.rglob("*.py") if "__pycache__" not in path.parts
    )


def generate_all(include_private: bool) -> List[ModuleStub]:
    """Return the stubs for every module in the package.

    Args:
        include_private: Whether to emit private names.

    Returns:
        One stub per module, in file order.
    """
    generator = StubGenerator(include_private=include_private)
    stubs: List[ModuleStub] = []
    for path in source_files():
        try:
            stubs.append(generator.generate(path))
        except SyntaxError as error:
            print(f"error: {path}: {error}", file=sys.stderr)
            raise SystemExit(1) from error
    return stubs


def write_all(stubs: Iterable[ModuleStub], output: pathlib.Path) -> int:
    """Write a stub tree, and the marker that says it is typed.

    The tree mirrors the package layout, so the output directory can be put
    on the path of a checker that wants stubs and nothing else.

    Args:
        stubs: The stubs to write.
        output: The directory to write them under.

    Returns:
        How many files were written, including the marker.
    """
    written = 0
    for stub in stubs:
        destination = output / stub.target
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(stub.text, encoding="utf-8")
        written += 1

    marker = output / "discretus" / "py.typed"
    marker.parent.mkdir(parents=True, exist_ok=True)
    marker.write_text("", encoding="utf-8")
    return written + 1


def collect_findings(stubs: Iterable[ModuleStub]) -> List[Finding]:
    """Return every finding from a set of stubs, in file and line order.

    Args:
        stubs: The stubs to read the findings from.

    Returns:
        The findings, sorted so that the report reads like the source.
    """
    findings: List[Finding] = []
    for stub in stubs:
        findings.extend(stub.findings)
    return sorted(findings, key=lambda finding: (finding.path, finding.line))


# ---------------------------------------------------------------------------
# The stub generator of the type checker
# ---------------------------------------------------------------------------


def run_stubgen(output: pathlib.Path) -> int:
    """Delegate the generation to the stub generator of the type checker.

    Running both and comparing is the point: two independent renderings of
    the same signatures that disagree mean one of them is wrong. The other
    tool imports what it can and parses what it cannot, so it sees defaults
    and aliases differently, and a difference is usually informative rather
    than a defect.

    Args:
        output: The directory to write under.

    Returns:
        A process exit status.
    """
    if shutil.which("stubgen") is None:
        print("error: stubgen is not installed; it comes with mypy", file=sys.stderr)
        print('  python3 -m pip install -e ".[dev]"', file=sys.stderr)
        return 2

    output.mkdir(parents=True, exist_ok=True)
    result = subprocess.run(
        [
            "stubgen",
            "--include-docstrings",
            "--output",
            str(output),
            str(PACKAGE_ROOT.relative_to(REPOSITORY_ROOT)),
        ],
        cwd=REPOSITORY_ROOT,
        check=False,
    )
    return result.returncode


# ---------------------------------------------------------------------------
# Comparison
# ---------------------------------------------------------------------------


def compare(
    stubs: Sequence[ModuleStub], output: pathlib.Path
) -> Tuple[List[str], List[str], List[str]]:
    """Compare freshly generated stubs against a previously written tree.

    Args:
        stubs: The freshly generated stubs.
        output: The directory holding the previous tree.

    Returns:
        The stubs that are new, the ones that differ, and the files in the
        tree that no source produces any more.
    """
    fresh: Dict[pathlib.Path, str] = {stub.target: stub.text for stub in stubs}

    added: List[str] = []
    changed: List[str] = []
    for target, text in sorted(fresh.items()):
        existing = output / target
        if not existing.exists():
            added.append(str(target))
        elif existing.read_text(encoding="utf-8") != text:
            changed.append(str(target))

    removed: List[str] = []
    if output.exists():
        for path in sorted(output.rglob("*.pyi")):
            if path.relative_to(output) not in fresh:
                removed.append(str(path.relative_to(output)))

    return added, changed, removed


