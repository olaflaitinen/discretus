DEFAULT_OUTPUT = REPOSITORY_ROOT / "build" / "stubs"

#: The notice every generated file carries. The license applies per file, so
#: a generated file needs it as much as a written one.
LICENSE_NOTICE = """# This Source Code Form is subject to the terms of the Mozilla Public
# License, v. 2.0. If a copy of the MPL was not distributed with this
# file, You can obtain one at https://mozilla.org/MPL/2.0/.
"""

#: The line that says a stub was generated, so that nobody edits one by hand
#: and expects the edit to survive.
GENERATED_MARKER = (
    "# Generated by scripts/generate_stubs.py. Do not edit.\n"
    "# The annotations live in the source; this file is derived from them.\n"
)

#: Special methods whose signature a checker already knows and whose absence
#: from a stub changes nothing. They are emitted anyway, because a subclass
