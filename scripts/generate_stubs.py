REPOSITORY_ROOT = pathlib.Path(__file__).resolve().parents[1]

#: The package to generate stubs for.
PACKAGE_ROOT = REPOSITORY_ROOT / "discretus"

#: Where the stub tree is written by default. Inside the build directory,
#: which .gitignore excludes, because a generated tree does not belong in the
