def main(argv: Optional[Sequence[str]] = None) -> int:
    """Generate the stubs, or audit the annotations behind them.

    Args:
        argv: The command line arguments, defaulting to the real ones.

    Returns:
        A process exit status.
    """
    arguments = build_parser().parse_args(argv)
    output = (REPOSITORY_ROOT / arguments.output).resolve()

    if not PACKAGE_ROOT.is_dir():
        print(f"error: {PACKAGE_ROOT} is not a directory", file=sys.stderr)
        return 2

    if arguments.use_stubgen:
        return run_stubgen(output)

    if arguments.print_module is not None:
        stub = StubGenerator(include_private=arguments.include_private).generate(
            resolve_module(arguments.print_module)
        )
        sys.stdout.write(stub.text)
        if stub.findings and not arguments.quiet:
            print(file=sys.stderr)
            for finding in stub.findings:
                print(f"  {finding.render()}", file=sys.stderr)
        return 1 if stub.findings and arguments.strict else 0

    stubs = generate_all(include_private=arguments.include_private)
    findings = collect_findings(stubs)

    if arguments.check:
        report_findings(findings)
        return 1 if findings else 0

    if arguments.diff:
        added, changed, removed = compare(stubs, output)
        if not (added or changed or removed):
            print(f"the tree in {output} is up to date")
            return 0
        for label, names in (
            ("new", added),
            ("different", changed),
            ("no longer produced", removed),
        ):
            if names:
                print(f"{len(names)} {label}:")
                for name in names:
                    print(f"  {name}")
        print()
        print("Regenerate with: scripts/generate_stubs.py")
        return 1

    written = write_all(stubs, output)
    if not arguments.quiet:
        report_written(stubs, output, written)
        print()
        report_findings(findings)

    return 1 if findings and arguments.strict else 0


if __name__ == "__main__":
    raise SystemExit(main())
