def build_parser() -> argparse.ArgumentParser:
    """Return the command line parser.

    Returns:
        The parser. The modes are mutually exclusive, because each one has a
        different notion of what success means.
    """
    parser = argparse.ArgumentParser(
        prog="scripts/generate_stubs.py",
        description=(
            "Generate type stubs for the library from its source, and "
            "report the annotations that are missing."
        ),
        epilog=(
            "The library is annotated inline and ships a py.typed marker, "
            "so the stubs are a convenience for tooling that cannot read "
            "inline annotations, and the audit is the part worth running."
        ),
    )
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument(
        "--check",
        action="store_true",
        help="report the missing annotations and write nothing",
    )
    modes.add_argument(
        "--diff",
        action="store_true",
        help="compare against the written tree and write nothing",
    )
    modes.add_argument(
        "--print",
        dest="print_module",
        metavar="MODULE",
        help="print the stub for one module, by import path or file path",
    )
    parser.add_argument(
        "--output",
        metavar="DIRECTORY",
        default=str(DEFAULT_OUTPUT.relative_to(REPOSITORY_ROOT)),
        help="where to write the stub tree, default build/stubs",
    )
    parser.add_argument(
        "--include-private",
        action="store_true",
        help="emit names with a leading underscore as well",
    )
    parser.add_argument(
        "--use-stubgen",
        action="store_true",
        help="delegate to the stub generator that comes with mypy",
    )
    parser.add_argument(
        "--strict",
        action="store_true",
        help="a missing annotation fails the run even outside --check",
    )
    parser.add_argument(
        "--quiet",
        action="store_true",
        help="print only what went wrong",
    )
    return parser


def resolve_module(name: str) -> pathlib.Path:
    """Return the source file a module argument denotes.

    Both forms are accepted, because both are natural: an import path is
    what a contributor reads in a traceback, and a file path is what an
    editor offers to copy.

    Args:
        name: An import path such as ``discretus.core.element``, or a file
            path such as ``discretus/core/element.py``.

    Returns:
        The source file.

    Raises:
        SystemExit: If no such module exists.
    """
    candidate = pathlib.Path(name)
    if candidate.suffix == ".py":
        resolved = (REPOSITORY_ROOT / candidate).resolve()
        if resolved.exists():
            return resolved

    parts = name.split(".")
    module = REPOSITORY_ROOT / pathlib.Path(*parts).with_suffix(".py")
    if module.exists():
        return module
    package = REPOSITORY_ROOT / pathlib.Path(*parts) / "__init__.py"
    if package.exists():
        return package

    print(f"error: no module named {name}", file=sys.stderr)
    raise SystemExit(2)


# ---------------------------------------------------------------------------
# Reporting
# ---------------------------------------------------------------------------


def report_findings(findings: Sequence[Finding]) -> None:
    """Print the findings, grouped so that the report reads like the source.

    Args:
        findings: The findings to print.
    """
    if not findings:
        print("every public signature is fully annotated")
        return

    label = "annotation is" if len(findings) == 1 else "annotations are"
    print(f"{len(findings)} {label} missing:")
    for finding in findings:
        print(f"  {finding.render()}")
    print()
    print("A typed package that omits an annotation is worse than an")
    print("untyped one, because a checker reports nothing and a reader")
    print("assumes the signature was checked.")


def report_written(
    stubs: Sequence[ModuleStub], output: pathlib.Path, written: int
) -> None:
    """Print what the generation produced.

    Args:
        stubs: The stubs that were written.
        output: Where they went.
        written: How many files were written.
    """
    definitions = sum(stub.emitted for stub in stubs)
    print(f"wrote {written} files to {output}")
    print(f"{len(stubs)} modules, {definitions} public definitions")
    print()
    print("Point a checker that wants stubs at the tree:")
    print(f"  MYPYPATH={output} mypy --no-site-packages your_code.py")


